import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = name => JSON.parse(readFileSync(resolve(root, 'data', name), 'utf8'));
const book = read('book-questions.json');
const exclusions = read('editorial-exclusions.json').groups.flatMap(group => group.ids);
const excluded = new Set(exclusions);
assert.equal(excluded.size, exclusions.length, 'Duplicate editorial exclusion');
assert.ok(exclusions.every(id => book.some(question => question.id === id)), 'Unknown editorial exclusion');

// Authored explanations fill gaps in the book; they never replace an original explanation.
const bookExplanations = read('book-explanations.json');
const supplements = new Map(bookExplanations.map(item => [item.id, item.explanation]));
assert.equal(supplements.size, bookExplanations.length, 'Duplicate supplementary explanation');
const retained = book.filter(question => !excluded.has(question.id)).map(question => {
  if (!supplements.has(question.id)) return question;
  assert.ok(!question.explanation, `Book already explains question: ${question.id}`);
  return { ...question, explanation: supplements.get(question.id), explanationSource: 'authored' };
});
for (const [id, explanation] of supplements) {
  assert.ok(retained.some(question => question.id === id), `Supplementary explanation for unknown or excluded question: ${id}`);
  assert.ok(explanation?.length >= 120, `Missing useful explanation: ${id}`);
}
// Only the original quiz-show questions belong in the active bank.
const questions = retained.sort((a, b) => a.id - b.id);
assert.ok(questions.length > 0, 'Missing book questions');
assert.equal(new Set(questions.map(question => question.id)).size, questions.length, 'Duplicate question ID');
assert.equal(new Set(questions.map(question => question.question.trim().toLocaleLowerCase('vi'))).size, questions.length, 'Duplicate question stem');
for (const question of questions) {
  assert.ok(Number.isSafeInteger(question.id) && question.id > 0);
  assert.deepEqual(Object.keys(question.options), ['A', 'B', 'C', 'D']);
  assert.ok(question.options[question.answer], `Invalid answer: ${question.id}`);
  assert.equal(new Set(Object.values(question.options).map(option => option.trim())).size, 4, `Duplicate choices: ${question.id}`);
  assert.ok(question.id <= 1044 && question.kind !== 'learning', `Not an original book question: ${question.id}`);
  assert.ok(Number.isSafeInteger(question.printedPage), `Missing book page: ${question.id}`);
}

const data = {
  title: 'Triệu phú · Học để hiểu',
  edition: 'Bộ câu hỏi Ai là triệu phú 2018 · Câu hỏi chọn lọc',
  defaultQuestionId: questions[0].id,
  total: questions.length,
  learningTotal: 0,
  bookTotal: retained.length,
  questions,
};
const output =
  '// Generated by npm run build:data from the archived book questions.\n' +
  '// Original IDs are preserved; editorial exclusions live in data/editorial-exclusions.json.\n' +
  `window.STUDY_DATA = ${JSON.stringify(data, null, 2)};\n`;
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(resolve(root, 'data/questions.js'), 'utf8'), output, 'Run npm run build:data to update the bundled bank');
} else {
  writeFileSync(resolve(root, 'data/questions.js'), output);
}
console.log(`Built ${questions.length} quiz-show questions from the book; ${excluded.size} book questions set aside. Authored learning questions are excluded.`);
